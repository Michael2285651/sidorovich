@bot.message_handler(commands=["start"])
async def start(message: types.Message):
    await bot.send_message(
        message.chat.id,
        "Здоров, сталкере.\n"
        "Я інформатор. Тут ти знайдеш відомості про Зону.",
        reply_markup=start_menu()
    )


# ====== CALLBACK ======
@bot.callback_query_handler(func=lambda call: True)
async def callbacks(call: types.CallbackQuery):
    chat_id = call.message.chat.id
    data = call.data

    await bot.answer_callback_query(call.id)

    # --- ДО КАТЕГОРІЙ ---
    if data == "start:next":
        await bot.edit_message_text(
            "Обери категорію:",
            chat_id,
            call.message.message_id,
            reply_markup=categories_menu()
        )
        return

    # --- СПИСОК ЕЛЕМЕНТІВ ---
    if data.startswith("cat:"):
        cat_key = data.split(":")[1]
        await bot.edit_message_text(
            f"{DATA[cat_key]['title']} — обери:",
            chat_id,
            call.message.message_id,
            reply_markup=items_menu(cat_key)
        )
        return

    # --- КОНКРЕТНИЙ ЕЛЕМЕНТ ---
    if data.startswith("item:"):
        _, cat_key, item_key = data.split(":")
        item = DATA[cat_key]["items"][item_key]

        await bot.edit_message_text(
            f"{item['name']}\n\n{item['text']}",
            chat_id,
            call.message.message_id,
            reply_markup=item_menu(cat_key)
        )
        return

    # --- НАЗАД ---
    if data.startswith("back:"):
        parts = data.split(":")

        if parts[1] == "categories":
            await bot.edit_message_text(
                "Обери категорію:",
                chat_id,
                call.message.message_id,
                reply_markup=categories_menu()
            )
            return

        if parts[1] == "cat":
            cat_key = parts[2]
            await bot.edit_message_text(
                f"{DATA[cat_key]['title']} — обери:",
                chat_id,
                call.message.message_id,
                reply_markup=items_menu(cat_key)
            )
            return


